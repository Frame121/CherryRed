#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REF="cbbddb6b08cc9900a87cccaa9b22bbe06aa4f50a"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
python3 - "$TMP" "$REF" <<'PY'
import pathlib, sys, urllib.request
out = pathlib.Path(sys.argv[1]); ref = sys.argv[2]
base = f"https://raw.githubusercontent.com/torvalds/linux/{ref}/drivers/gpu/drm/amd/include/asic_reg/gc/"
for name in ("gc_11_0_0_offset.h", "gc_11_0_0_sh_mask.h", "gc_11_0_0_default.h"):
    data = urllib.request.urlopen(base + name, timeout=30).read()
    (out / name).write_bytes(data)
    print(f"Fetched {name}: {len(data)} bytes")
PY
cd "$ROOT"
python3 tools/gen_gc_regs.py "$TMP/gc_11_0_0_offset.h" "$TMP/gc_11_0_0_sh_mask.h" tools/gc_regs_spec.txt "$TMP/gc_11_0_0_default.h" > "$TMP/generated.h"
sed 's/REDNAVI_GC_REGS_H/REDNAVI_GC_REGS_NAVI33_H/' "$TMP/generated.h" | \
  sed "1s@.*@// Generated by tools/gen_gc_regs.py from torvalds/linux ${REF} gc_11_0_0 headers for Navi 33 GC 11.0.2 (MIT, see NOTICE). Do not edit.@" \
  > RedNavi/gc_regs_navi33.h
printf 'Wrote %s/RedNavi/gc_regs_navi33.h from Linux %s\n' "$ROOT" "$REF"
