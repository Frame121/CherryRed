#!/usr/bin/env python3
"""gen_regs.py - generate src/dcn321/dcn321_regs.h from Linux's DCN 3.2.1 register headers.

Mirrors tools/dcn41/gen_regs.py (the DCN 4.1 generator) for DCN 3.2.1, the Display Core
the RX 7600 (Navi 33) actually uses (see RX7600-Linux-Evidence/dcn321-dependency-map.md).

CLI:
  python3 tools/dcn321/gen_regs.py --offset <dcn_3_2_1_offset.h> \
      --shmask <dcn_3_2_1_sh_mask.h> --spec <spec.json> --out <dcn321_regs.h>
  python3 tools/dcn321/gen_regs.py ... --check   # exit 1 if --out differs from a fresh generation

Inputs (two DCN 3.2.1 asic_reg headers; these are materializable on demand from the blob:none
evidence clone via `git show <commit>:<path>`, or from any full Linux/amdgpu checkout):
  drivers/gpu/drm/amd/include/asic_reg/dcn/dcn_3_2_1_offset.h   regXXX offsets + regXXX_BASE_IDX
  drivers/gpu/drm/amd/include/asic_reg/dcn/dcn_3_2_1_sh_mask.h  XXX__FIELD_MASK / XXX__FIELD__SHIFT

Every offset is emitted per instance straight from the header (never from a stride); field
masks/shifts from the instance-0 name (the convention of Linux's own DCN321 mask lists). The
generator REFUSES when an instance is missing, when instances disagree on BASE_IDX, or when
another instance's mask/shift differs from instance 0's. No arithmetic other than parsing.

The register SPEC is data (spec.json: a list of [group, prefix, count, reg, [fields]]), not
hard-coded, so the same generator serves the display bring-up and can be extended as more DCN
3.2.1 registers are needed. The test in src/dcn321/tests/ exercises this logic against a
synthetic fixture (so the generator is proven without the real headers). The committed
src/dcn321/dcn321_regs.h was generated from the real headers (see its provenance line); that
header is not yet validated against the physical card.
"""
import argparse
import json
import re
import sys
from pathlib import Path

DEF = re.compile(r"^#define\s+(\w+)\s+(0x[0-9a-fA-F]+|\d+)L?\s*$")


def parse(text):
    d = {}
    for line in text.splitlines():
        m = DEF.match(line.strip())
        if m:
            d[m.group(1)] = int(m.group(2), 0)
    return d


def generate(offset_text, shmask_text, spec, prefix="DCN321", provenance=""):
    off = parse(offset_text)
    msk = parse(shmask_text)
    out = [
        f"/* {prefix.lower()}_regs.h - GENERATED by tools/dcn321/gen_regs.py; do not edit (regenerate, then --check).",
        " *",
        " * Source: Linux DCN 3.2.1 asic_reg headers (dcn_3_2_1_offset.h + dcn_3_2_1_sh_mask.h, MIT).",
        " * Each register offset is the header's regNAME value for that instance, relative to the DCN segment named",
        " * by its _BASE_IDX; the absolute BAR5 dword is seg[BASE_IDX] + offset. Field masks and shifts are the",
        " * instance-0 names; the generator refused if any instance disagreed.",
        " *",
    ]
    if provenance:
        out.append(" * Provenance: " + provenance)
        out.append(" *")
    out += [
        f"#ifndef {prefix}_REGS_H",
        f"#define {prefix}_REGS_H",
        "",
        f"#define {prefix}_BAD_OFFSET 0xFFFFFFFFu",
        "",
    ]
    max_by_base = {}
    for group, pat, count, reg, fields in spec:
        names = [f"reg{pat.format(i=i)}{reg}" if pat else f"reg{reg}" for i in range(count)]
        vals, bases = [], set()
        for n in names:
            if n not in off or f"{n}_BASE_IDX" not in off:
                raise SystemExit(f"gen_regs: {n} or its _BASE_IDX missing from offset header: refusing")
            vals.append(off[n])
            bases.add(off[f"{n}_BASE_IDX"])
        if len(bases) != 1:
            raise SystemExit(f"gen_regs: {reg}: instances disagree on BASE_IDX {sorted(bases)}: refusing")
        base = bases.pop()
        max_by_base[base] = max(max_by_base.get(base, 0), max(vals))
        cname = f"{prefix}_{group}_{reg}" if pat else f"{prefix}_{reg}"
        out.append("/* " + ", ".join(f"{n} 0x{v:04x}" for n, v in zip(names, vals)) + f"; BASE_IDX {base} */")
        if pat:
            chain = " : ".join(f"(i) == {i} ? 0x{v:04x}u" for i, v in enumerate(vals))
            out.append(f"#define {cname}(i) ((unsigned)({chain} : {prefix}_BAD_OFFSET))")
        else:
            out.append(f"#define {cname} 0x{vals[0]:04x}u")
        out.append(f"#define {cname}_BASE_IDX {base}u")
        for fld in fields:
            mname0 = (f"{pat.format(i=0)}{reg}__{fld}" if pat else f"{reg}__{fld}")
            if f"{mname0}_MASK" not in msk or f"{mname0}__SHIFT" not in msk:
                raise SystemExit(f"gen_regs: {mname0}_MASK/__SHIFT missing from sh_mask header: refusing")
            m0, s0 = msk[f"{mname0}_MASK"], msk[f"{mname0}__SHIFT"]
            if pat:
                for i in range(1, count):
                    mi = f"{pat.format(i=i)}{reg}__{fld}"
                    if f"{mi}_MASK" in msk and (msk[f"{mi}_MASK"], msk[f"{mi}__SHIFT"]) != (m0, s0):
                        raise SystemExit(f"gen_regs: {mi} differs from instance 0: refusing")
            out.append(f"#define {cname}__{fld}_MASK 0x{m0:08x}u  /* {mname0}_MASK */")
            out.append(f"#define {cname}__{fld}__SHIFT {s0}u")
        out.append("")
    out.append("/* largest offset used per BASE_IDX: the bring-up checks seg[b] + this is inside the BAR5 window */")
    for b in sorted(max_by_base):
        out.append(f"#define {prefix}_MAX_OFFSET_BASE{b} 0x{max_by_base[b]:04x}u")
    out.append(f"#define {prefix}_BASE_IDX_USED_MASK 0x{sum(1 << b for b in max_by_base):x}u")
    out += ["", f"#endif /* {prefix}_REGS_H */", ""]
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate a DCN 3.2.1 register header (mirrors dcn41).")
    ap.add_argument("--offset", required=True, help="path to dcn_3_2_1_offset.h")
    ap.add_argument("--shmask", required=True, help="path to dcn_3_2_1_sh_mask.h")
    ap.add_argument("--spec", required=True, help="path to spec.json (list of [group,prefix,count,reg,[fields]])")
    ap.add_argument("--out", required=True, help="output header path")
    ap.add_argument("--prefix", default="DCN321", help="macro prefix (default DCN321)")
    ap.add_argument("--provenance", default="",
                    help="one-line source provenance (commit/clone + blob SHAs) embedded in the header")
    ap.add_argument("--check", action="store_true", help="exit 1 if --out differs from a fresh generation")
    args = ap.parse_args(argv)

    spec = json.loads(Path(args.spec).read_text(encoding="utf-8"))
    text = generate(Path(args.offset).read_text(encoding="utf-8"),
                    Path(args.shmask).read_text(encoding="utf-8"),
                    spec, args.prefix, args.provenance)
    if args.check:
        cur = Path(args.out).read_text(encoding="utf-8") if Path(args.out).exists() else ""
        if cur != text:
            print(f"gen_regs --check: {args.out} is STALE (regenerate)")
            return 1
        print(f"gen_regs --check: {Path(args.out).name} matches a fresh generation")
        return 0
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"gen_regs: wrote {args.out} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
