#!/usr/bin/env python3
"""Extract one component of an AMD PSP firmware file into a C header for local builds.

The header is git-ignored: firmware is not redistributed from this repository.

    python3 tools/gen_psp_fw_header.py psp_13_0_10_sos.bin KDB RedNavi/psp_kdb.h
"""
import struct
import sys

NAMES = ["UNKNOWN", "SOS", "SYS_DRV", "KDB", "TOC", "SPL", "RL", "SOC_DRV", "INTF_DRV",
         "DBG_DRV", "RAS_DRV", "IPKEYMGR_DRV", "SPDM_DRV"]


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    path, comp, out = sys.argv[1:]
    b = open(path, "rb").read()
    uoff, = struct.unpack_from("<I", b, 24)
    count, = struct.unpack_from("<I", b, 32)
    for i in range(count):
        t, ver, off, size = struct.unpack_from("<IIII", b, 36 + 16 * i)
        if NAMES[t] == comp:
            data = b[uoff + off:uoff + off + size]
            with open(out, "w") as f:
                f.write(f"// Generated by tools/gen_psp_fw_header.py from {path}. Do not commit.\n")
                f.write(f"static const unsigned int kRNPspKdbVersion = 0x{ver:x};\n")
                f.write("static const unsigned char kRNPspKdb[] = {\n")
                for j in range(0, len(data), 16):
                    f.write("    " + ", ".join(f"0x{x:02x}" for x in data[j:j + 16]) + ",\n")
                f.write("};\n")
            print(f"{comp}: {len(data)} bytes, version 0x{ver:x} -> {out}")
            return
    sys.exit(f"component {comp} not found")


if __name__ == "__main__":
    main()
